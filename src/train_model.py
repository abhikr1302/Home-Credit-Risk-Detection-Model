RANDOM_STATE = 42

VALIDATION_SIZE = 0.20

EXPECTED_FEATURE_COUNT = 50

TARGET_COLUMN = "target"

ID_COLUMN = "sk_id_curr"

# Decision thresholds to evaluate.
#
# 0.50 is retained as the standard baseline.
# Lower thresholds increase recall and usually decrease
# precision.

THRESHOLDS = [
    0.20,
    0.25,
    0.30,
    0.35,
    0.40,
    0.45,
    0.50,
    0.55,
    0.60,
]


